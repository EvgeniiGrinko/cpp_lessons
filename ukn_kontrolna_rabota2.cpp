#include <iostream>
#include <clocale>

using namespace std;

/*
    Задание 3:
    Да се напише алгоритъм, която въвежда n брой числа от 
    клавиатура и намира сумата само на онези от тях, които 
    са положителни
 */

int main() {
    setlocale(LC_ALL, "");

    int numberOfDigits;

    cout << "Въведете брой числа: " << endl;
    cin >> numberOfDigits;

    double sum = 0;
    double number;
    int count = 0;
    

    if (numberOfDigits < 0) {
        cout << "Възникна грешка: невалиден брой числа" << endl;
        return 1;
    } else {
        for (int i = 0; i < numberOfDigits; i++) {
            
            cout << "Въведете стойността на " << i << " число: " << endl;
            cin >> number;

            if (number > 0) {
                count++;
                sum += number;
            }
        }
    }

    if (count == 0) {
        cout << "Няма положителни числа";
    } else {
        cout << "Обща сума на всички положителни числа: " << sum << endl;
    }

    return 0;
}

