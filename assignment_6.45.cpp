#include <iostream>

using namespace std;

/**
 * Задача 6.45: Управление на продажби с бонус система
 * Програма за отчитане на дневни продажби с динамична бонус система за
 * служителите.
 * Програмата трябва да обработва продажбите на един служител за деня, докато
 * потребителят не въведе отрицателна сума за продажба (сигнал за край на деня). За
 * всяка продажба:
 * Продажба > 1000 лв.: Бонус от 10% от сумата.
 * Продажба 500 - 1000 лв.: Бонус от 5% от сумата.
 * Продажба < 500 лв.: 0 бонус. Изведете общата сума на продажбите за деня и общия
 * натрупан бонус.
 * Упътване: Използвайте do-while цикъл, за да прочетете поне една продажба.
 * Условието на while трябва да проверява дали въведената сума е положителна. Вътре
 * в цикъла използвайте if-else за прилагане на правилната логика за бонус.
 * Натрупвайте общите суми в две отделни променливи (totalSales и totalBonus).
 */
int main() {
    double sale;
    double totalSales = 0.0;
    double totalBonus = 0.0;

    do {
        cout << "Enter sale amount (negative to end): ";
        cin >> sale;

        if (sale > 0) {
            totalSales += sale;
            if (sale > 1000) {
                totalBonus += sale * 0.10;
            } else if (sale >= 500 && sale <= 1000) {
                totalBonus += sale * 0.05;
            } // else bonus is 0 for sale < 500
        }
    } while (sale >= 0);

    cout << "Total sales: " << totalSales << endl;
    cout << "Total accumulated bonus: " << totalBonus << endl;

    return 0;
}
